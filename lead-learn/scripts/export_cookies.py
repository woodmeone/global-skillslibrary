"""从 Playwright 持久化 profile 导出 Netscape cookies.txt，供 yt-dlp 使用。

为什么不用 --cookies-from-browser：
  本机 Chrome/Edge 的 Cookies 库被独占锁住，yt-dlp 复制失败。
  但我们自己的持久化 profile 是我们开的浏览器，能直接读。
"""

from __future__ import annotations

import asyncio
import os
import sys
from pathlib import Path

from playwright.async_api import async_playwright

from paths import CHROMIUM  # noqa: E402
PROFILE_ROOT = Path(
    os.path.expandvars(r"%LOCALAPPDATA%\dsh-bili-humanism\browser-profiles")
)
from paths import OUT  # noqa: E402


def to_netscape(cookies: list[dict]) -> str:
    """转成 Netscape cookies.txt 格式（yt-dlp 认）。"""
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by favorites.py export-cookies",
        "",
    ]
    for c in cookies:
        domain = c.get("domain", "")
        if not domain:
            continue
        # Netscape 要求域前导点表示子域共享
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        path = c.get("path", "/") or "/"
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = c.get("expires")
        # session cookie 用 0
        if not isinstance(expires, (int, float)) or expires < 0:
            expires = 0
        else:
            expires = int(expires)
        name = c.get("name", "")
        value = c.get("value", "")
        lines.append(
            f"{domain}\t{include_sub}\t{path}\t{secure}\t{expires}\t{name}\t{value}"
        )
    return "\n".join(lines) + "\n"


async def main(platform: str) -> int:
    profile = PROFILE_ROOT / platform
    if not profile.exists():
        print(f"profile 不存在: {profile}（先跑 login）")
        return 1

    async with async_playwright() as pw:
        ctx = await pw.chromium.launch_persistent_context(
            user_data_dir=str(profile),
            executable_path=CHROMIUM,
            headless=True,
        )
        cookies = await ctx.cookies()
        await ctx.close()

    text = to_netscape(cookies)
    OUT.mkdir(parents=True, exist_ok=True)
    dest = OUT / f"{platform}-cookies.txt"
    dest.write_text(text, encoding="utf-8")
    print(f"[{platform}] {len(cookies)} 个 cookie → {dest}")
    keys = sorted({c["name"] for c in cookies})
    important = [
        k for k in keys
        if any(x in k.lower() for x in ("sess", "sid", "uid", "ttwid", "passport", "odin"))
    ]
    print(f"  关键项: {important[:12]}")
    return 0


if __name__ == "__main__":
    plat = sys.argv[1] if len(sys.argv) > 1 else "douyin"
    sys.exit(asyncio.run(main(plat)))
